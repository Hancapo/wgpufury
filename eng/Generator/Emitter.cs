    private sealed class Plan
    {
        public List<string> Signature { get; } = [];
        public List<string> ParamNames { get; } = [];
        public List<string> Fixed { get; } = [];
        public List<string> Usings { get; } = [];
        public List<string> Args { get; } = [];
        public bool Generic { get; set; }
    }

    /// <summary>
    /// Plans a friendly overload: count+pointer pairs become spans, void*+size pairs become generic spans,
    /// const struct pointers become <c>in</c> parameters and string views become UTF-8 spans (or strings).
    /// Returns null when nothing would change.
    /// </summary>
    private Plan? BuildPlan(List<ParamDef> ps, bool stringMode)
    {
        var plan = new Plan();
        bool changed = false;
        bool hasString = false;
        for (int i = 0; i < ps.Count; i++)
        {
            ParamDef p = ps[i];
            ParamDef? q = i + 1 < ps.Count ? ps[i + 1] : null;
            string pn = Naming.Identifier(p.Name);

            if (q != null && IsCountPair(p, q))
            {
                string elem = Cs(q.Type with { Pointers = q.Type.Pointers - 1 });
                string qn = Naming.Identifier(q.Name);
                plan.Signature.Add($"{(q.Type.PointeeConst ? "ReadOnlySpan" : "Span")}<{elem}> {qn}");
                plan.ParamNames.Add(q.Name);
                plan.Fixed.Add($"{elem}* __{q.Name} = {qn}");
                plan.Args.Add($"({Cs(p.Type)}){qn}.Length");
                plan.Args.Add($"__{q.Name}");
                changed = true;
                i++;
            }
            else if (q != null && !plan.Generic && p.Type is { Base: "void", Pointers: 1 } && q.Type is { Base: "size_t", Pointers: 0 } && q.Name is "size" or "dataSize")
            {
                plan.Generic = true;
                plan.Signature.Add($"{(p.Type.PointeeConst ? "ReadOnlySpan" : "Span")}<TData> {pn}");
                plan.ParamNames.Add(p.Name);
                plan.Fixed.Add($"TData* __{p.Name} = {pn}");
                plan.Args.Add($"__{p.Name}");
                plan.Args.Add($"(nuint){pn}.Length * (nuint)sizeof(TData)");
                changed = true;
                i++;
            }
            else if (p.Type is { Pointers: 1, PointeeConst: true } && _structs.ContainsKey(p.Type.Base))
            {
                plan.Signature.Add($"in {p.Type.Base} {pn}");
                plan.ParamNames.Add(p.Name);
                plan.Fixed.Add($"{p.Type.Base}* __{p.Name} = &{pn}");
                plan.Args.Add($"__{p.Name}");
                changed = true;
            }
            else if (IsStringView(p.Type))
            {
                hasString = true;
                plan.ParamNames.Add(p.Name);
                if (stringMode)
                {
                    plan.Signature.Add($"string? {pn}");
                    plan.Usings.Add($"using Utf8Scratch __{p.Name} = new({pn}, stackalloc byte[Utf8Scratch.StackBufferSize]);");
                    plan.Args.Add($"__{p.Name}.View");
                }
                else
                {
                    plan.Signature.Add($"ReadOnlySpan<byte> {pn}");
                    plan.Fixed.Add($"byte* __{p.Name} = {pn}");
                    plan.Args.Add($"new WGPUStringView(__{p.Name}, (nuint){pn}.Length)");
                }

                changed = true;
            }
            else
            {
                plan.Signature.Add($"{Cs(p.Type)} {pn}");
                plan.ParamNames.Add(p.Name);
                plan.Args.Add(pn);
            }
        }

        if (stringMode && !hasString)
        {
            return null;
        }

        return changed ? plan : null;
    }

    private static bool IsCountPair(ParamDef count, ParamDef array) =>
        count.Type is { Pointers: 0, Base: "size_t" or "uint32_t" }
        && count.Name.EndsWith("Count", StringComparison.Ordinal)
        && array.Type is { Pointers: 1 } && array.Type.Base is not ("void" or "char")
        && array.Name.StartsWith(count.Name[..^"Count".Length], StringComparison.Ordinal);

