    /// <summary>A C program printing sizeof/offsetof of every named struct as JSON.</summary>
    public string EmitLayoutProbeC()
    {
        var sb = new StringBuilder();
        sb.Append($$"""
            /* Generated by eng/Generator from the wgpu-native {{_version}} headers. Do not edit. */
            #include <stdio.h>
            #include <stddef.h>
            #include "webgpu/wgpu.h"

            static int first_struct = 1;
            static int first_field;
            #define S(T) printf("%s\n  \"%s\": {\"size\": %u, \"fields\": {", first_struct ? "" : ",", #T, (unsigned)sizeof(T)); first_struct = 0; first_field = 1;
            #define F(T, f) printf("%s\"%s\": %u", first_field ? "" : ", ", #f, (unsigned)offsetof(T, f)); first_field = 0;
            #define E() printf("}" "}");

            int main(void)
            {
                printf("{");

            """);
        foreach (StructDef s in _m.Structs.Where(s => !s.IsUnion))
        {
            sb.Append($"    S({s.Name})");
            foreach (FieldDef f in s.Fields)
            {
                sb.Append($" F({s.Name}, {f.Name})");
            }

            sb.Append(" E()\n");
        }

        sb.Append("    printf(\"\\n}\\n\");\n    return 0;\n}\n");
        return sb.ToString();
    }

