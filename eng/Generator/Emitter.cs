using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace WGpuFury.Generator;

/// <summary>Turns a parsed <see cref="HeaderModel"/> into C# source.</summary>
internal sealed partial class Emitter
{
    private const string Indent = "    ";
    private const string Lib = "WGPU";

    private readonly HeaderModel _m;
    private readonly string _version;
    private readonly Dictionary<string, EnumDef> _enums = [];
    private readonly Dictionary<string, string> _enumRedirects = [];
    private readonly Dictionary<string, (EnumDef Owner, EnumMember Member)> _enumMembers = [];
    private readonly Dictionary<string, StructDef> _structs;
    private readonly Dictionary<string, CallbackDef> _callbacks;
    private readonly Dictionary<string, HandleDef> _handles;
    private readonly Dictionary<string, InitMacro> _initByStruct = [];
    private readonly HashSet<string> _constants;
    private readonly Dictionary<string, bool> _hasDefaults = [];

    private readonly HashSet<string> _unimplemented;

    public Emitter(HeaderModel model, string version, IEnumerable<string> unimplemented)
    {
        _m = model;
        _unimplemented = unimplemented.ToHashSet();
        foreach (string name in _unimplemented.Where(n => !model.Functions.Any(f => f.Name == n)))
        {
            throw new FormatException($"unimplemented.txt lists unknown function {name}");
        }

        _version = version;
        _structs = model.Structs.ToDictionary(s => s.Name);
        _callbacks = model.Callbacks.ToDictionary(c => c.Name);
        _handles = model.Handles.ToDictionary(h => h.Name);
        _constants = model.Constants.Select(c => c.Name).ToHashSet();
        foreach (InitMacro init in model.InitMacros.Values)
        {
            _initByStruct[init.StructName] = init;
        }

        MergeEnums();
    }

    /// <summary>
    /// wgpu.h extends standard enums by declaring e.g. <c>WGPUNativeSType</c> whose members are spelled
    /// <c>WGPUSType_*</c>. Those members are folded into the enum they extend, exactly like C treats them.
    /// </summary>
    private void MergeEnums()
    {
        foreach (EnumDef e in _m.Enums)
        {
            _enums[e.Name] = e;
        }

        foreach (EnumDef e in _m.Enums.ToList())
        {
            var prefixes = e.Members.Where(x => !IsForce32(x)).Select(x => x.CName[..x.CName.IndexOf('_', StringComparison.Ordinal)]).Distinct().ToList();
            if (prefixes is [var prefix] && prefix != e.Name && _enums.TryGetValue(prefix, out EnumDef? target))
            {
                target.Members.AddRange(e.Members.Where(x => !IsForce32(x)));
                _enums.Remove(e.Name);
                _enumRedirects[e.Name] = target.Name;
            }
        }

        foreach (EnumDef e in _enums.Values)
        {
            foreach (EnumMember member in e.Members)
            {
                if (!member.CName.StartsWith(e.Name + "_", StringComparison.Ordinal))
                {
                    throw new FormatException($"Enum member {member.CName} does not start with {e.Name}_");
                }

                _enumMembers[member.CName] = (e, member);
            }
        }
    }

    private static bool IsForce32(EnumMember m) => m.CName.EndsWith("_Force32", StringComparison.Ordinal);

    private static string MemberName(EnumDef e, EnumMember m)
    {
        string name = m.CName[(e.Name.Length + 1)..];
        return char.IsDigit(name[0]) ? "_" + name : name;
    }

    private string Header(string usings = "using System;\nusing System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\n") =>
        $"""
        // <auto-generated>
        //   Generated by eng/Generator from the wgpu-native {_version} headers (webgpu.h, wgpu.h).
        //   Do not edit by hand; run `dotnet run --project eng/Generator` instead.
        // </auto-generated>
        #nullable enable
        #pragma warning disable CS1591, CS1573, WGPUFURY001
        {usings}
        namespace WGpuFury;


        """;

    // ---------------------------------------------------------------- types

    private string Cs(CType t) => BaseCs(t.Base) + new string('*', t.Pointers);

    private string BaseCs(string b) => b switch
    {
        "void" => "void",
        "char" => "byte",
        "int" => "int",
        "float" => "float",
        "double" => "double",
        "uint8_t" => "byte",
        "int8_t" => "sbyte",
        "uint16_t" => "ushort",
        "int16_t" => "short",
        "uint32_t" => "uint",
        "int32_t" => "int",
        "uint64_t" => "ulong",
        "int64_t" => "long",
        "size_t" => "nuint",
        "WGPUBool" => "WGPUBool",
        _ when _m.Aliases.TryGetValue(b, out CType? aliased) => Cs(aliased),
        _ when _callbacks.TryGetValue(b, out CallbackDef? cb) => FunctionPointer(cb),
        _ when _enumRedirects.TryGetValue(b, out string? target) => target,
        _ when _enums.ContainsKey(b) || _structs.ContainsKey(b) || _handles.ContainsKey(b) => b,
        _ => throw new FormatException($"Unknown C type '{b}'"),
    };

    private string FunctionPointer(CallbackDef cb) =>
        $"delegate* unmanaged[Cdecl]<{string.Join(", ", cb.Params.Select(p => Cs(p.Type)).Append(Cs(cb.Return)))}>";

    private bool IsStringView(CType t) => t is { Base: "WGPUStringView", Pointers: 0 };

    // ---------------------------------------------------------------- enums & flags

    public string EmitEnums()
    {
        var sb = new StringBuilder(Header("using System;\n"));
        foreach (EnumDef e in _enums.Values)
        {
            DocText.Write(sb, "", e.Doc, extra: $"<c>{e.Name}</c> from <c>{e.Header}</c>.");
            if (e.IsFlags)
            {
                sb.Append("[Flags]\n");
            }

            sb.Append($"public enum {e.Name}{(e.IsFlags ? " : ulong" : "")}\n{{\n");
            foreach (EnumMember member in e.Members.Where(x => !IsForce32(x)))
            {
                DocText.Write(sb, Indent, member.Doc);
                sb.Append($"{Indent}{MemberName(e, member)} = {member.Value},\n");
            }

            sb.Append("}\n\n");
        }

        // For the argument checks of the methods on handles (see Checks).
        sb.Append("/// <summary>Whether enum values are defined, for the argument checks of the methods on handles.</summary>\n");
        sb.Append("internal static class WGPUEnumChecks\n{\n");
        foreach (EnumDef e in _enums.Values.Where(e => IsCheckedEnum(e) && IsPassedByValue(e)))
        {
            string members = string.Join(" or ", e.Members.Where(x => !IsForce32(x)).Select(x => $"{e.Name}.{MemberName(e, x)}"));
            sb.Append($"{Indent}internal static bool IsDefined({e.Name} value) => value is {members};\n\n");
        }

        return sb.ToString().TrimEnd() + "\n}\n";
    }

    private bool IsPassedByValue(EnumDef e) =>
        _m.Functions.Any(f => f.Params.Any(p => p.Type.Pointers == 0 && _enumRedirects.GetValueOrDefault(p.Type.Base, p.Type.Base) == e.Name));

    // Flags combine freely. Feature names stay open-ended: asking whether an unknown feature is supported must
    // keep answering false, not throw.
    private static bool IsCheckedEnum(EnumDef e) =>
        !e.IsFlags && !e.Name.EndsWith("FeatureName", StringComparison.Ordinal) && e.Members.Any(x => !IsForce32(x));

    // ---------------------------------------------------------------- structs

    public string EmitStructs()
    {
        var sb = new StringBuilder(Header());
        foreach (StructDef s in _m.Structs)
        {
            DocText.Write(sb, "", s.Doc, extra: s.IsUnion ? null : $"<c>{s.Name}</c> from <c>{s.Header}</c>.");
            sb.Append(s.IsUnion ? "[StructLayout(LayoutKind.Explicit)]\n" : "[StructLayout(LayoutKind.Sequential)]\n");
            sb.Append($"public unsafe partial struct {s.Name}\n{{\n");
            bool anyInit = false;
            var inits = InitializersFor(s);
            for (int i = 0; i < s.Fields.Count; i++)
            {
                FieldDef f = s.Fields[i];
                if (i > 0)
                {
                    sb.Append('\n');
                }

                string? typeNote = _callbacks.ContainsKey(f.Type.Base)
                    ? $"C type: <c>{f.Type.Base}</c>. Point it at a static <c>[UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]</c> method."
                    : null;
                DocText.Write(sb, Indent, f.Doc, extra: typeNote);
                if (s.IsUnion)
                {
                    sb.Append($"{Indent}[FieldOffset(0)]\n");
                }

                if (f.ArrayLength > 0)
                {
                    string element = Cs(f.Type);
                    if (element is not ("float" or "double" or "byte" or "sbyte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong"))
                    {
                        throw new FormatException($"{s.Name}.{f.Name}: fixed-size arrays of {element} are not supported");
                    }

                    sb.Append($"{Indent}public fixed {element} {Naming.Pascal(f.Name)}[{f.ArrayLength}];\n");
                    continue;
                }

                sb.Append($"{Indent}public {Cs(f.Type)} {Naming.Pascal(f.Name)}");
                if (inits.TryGetValue(f.Name, out string? init))
                {
                    sb.Append(" = ").Append(init);
                    anyInit = true;
                }

                sb.Append(";\n");
            }

            if (anyInit)
            {
                sb.Append($"\n{Indent}/// <summary>Creates a <see cref=\"{s.Name}\"/> with the defaults of <c>{_initByStruct[s.Name].MacroName}</c>.</summary>\n");
                sb.Append($"{Indent}/// <remarks><c>default({s.Name})</c>, <c>stackalloc</c> and new arrays are zero-filled instead.</remarks>\n");
                sb.Append($"{Indent}public {s.Name}()\n{Indent}{{\n{Indent}}}\n");
            }

            sb.Append("}\n\n");
        }

        return sb.ToString().TrimEnd() + "\n";
    }

    private Dictionary<string, string> InitializersFor(StructDef s)
    {
        var result = new Dictionary<string, string>();
        if (!_initByStruct.TryGetValue(s.Name, out InitMacro? init))
        {
            return result;
        }

        var fieldNames = s.Fields.Select(f => f.Name).ToHashSet();
        foreach (var (field, value) in init.Value.Fields)
        {
            if (!fieldNames.Contains(field))
            {
                throw new FormatException($"{init.MacroName} initializes unknown field {s.Name}.{field}");
            }

            CType type = s.Fields.First(f => f.Name == field).Type;
            if (InitExpression(value, type) is { } expr)
            {
                result[field] = expr;
            }
        }

        return result;
    }

    private bool HasDefaults(string structName)
    {
        if (_hasDefaults.TryGetValue(structName, out bool cached))
        {
            return cached;
        }

        _hasDefaults[structName] = false; // recursion guard
        bool value = _structs.TryGetValue(structName, out StructDef? s) && InitializersFor(s).Count > 0;
        _hasDefaults[structName] = value;
        return value;
    }

    /// <summary>The C# initializer for a value from an INIT macro, or null when it is zero (the C# default).</summary>
    private string? InitExpression(InitValue value, CType type)
    {
        if (value is InitValue.Struct nested)
        {
            var parts = new List<string>();
            StructDef def = _structs[nested.StructName];
            foreach (var (field, v) in nested.Fields)
            {
                if (InitExpression(v, def.Fields.First(f => f.Name == field).Type) is { } e)
                {
                    parts.Add($"{Naming.Pascal(field)} = {e}");
                }
            }

            return parts.Count == 0 && !HasDefaults(nested.StructName) ? null : $"new {nested.StructName} {{ {string.Join(", ", parts)} }}";
        }

        string text = ((InitValue.Scalar)value).Text;
        Match cast = CastRegex().Match(text);
        if (cast.Success)
        {
            text = cast.Groups[1].Value.Trim();
        }

        if (text is "NULL" or "WGPU_FALSE" or "_wgpu_STRUCT_ZERO_INIT" || text.StartsWith("_wgpu_ENUM_ZERO_INIT(", StringComparison.Ordinal) || IsZeroLiteral(text))
        {
            return null;
        }

        if (text == "WGPU_TRUE")
        {
            return "true";
        }

        if (_m.InitMacros.TryGetValue(text, out InitMacro? macro))
        {
            return HasDefaults(macro.StructName) ? $"new {macro.StructName}()" : null;
        }

        if (_constants.Contains(text))
        {
            return $"{Lib}.{text}";
        }

        if (_enumMembers.TryGetValue(text, out var em))
        {
            return IsZeroLiteral(em.Member.Value) ? null : $"{em.Owner.Name}.{MemberName(em.Owner, em.Member)}";
        }

        if (NumberRegex().IsMatch(text))
        {
            if (type.Base is "float" or "double")
            {
                string number = text.TrimEnd('f');
                return (number.EndsWith('.') ? number + "0" : number) + (type.Base == "float" ? "f" : "");
            }

            return text;
        }

        throw new FormatException($"Unsupported INIT value '{text}' for type {type}");
    }

    private static bool IsZeroLiteral(string text) => ZeroRegex().IsMatch(text.Trim());

    // ---------------------------------------------------------------- handles

    private HandleDef? OwnerOf(FunctionDef f)
    {
        if (f.Params.Count == 0 || f.Params[0].Type.Pointers != 0 || !_handles.TryGetValue(f.Params[0].Type.Base, out HandleDef? h))
        {
            return null;
        }

        return f.Name.StartsWith("wgpu" + h.Name[4..], StringComparison.Ordinal) ? h : null;
    }

    public string EmitHandles()
    {
        var sb = new StringBuilder(Header("using System;\nusing System.Diagnostics;\nusing System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\n"));
        foreach (HandleDef h in _m.Handles)
        {
            List<FunctionDef> methods = _m.Functions.Where(f => OwnerOf(f) == h).ToList();
            FunctionDef? release = methods.FirstOrDefault(f => f.Name == $"wgpu{h.Name[4..]}Release");

            DocText.Write(sb, "", h.Doc, extra: $"Opaque handle <c>{h.Name}</c> from <c>{h.Header}</c>.");
            sb.Append($"[DebuggerDisplay(\"{h.Name}({{Handle}})\")]\n");
            sb.Append($"public readonly unsafe partial struct {h.Name} : IEquatable<{h.Name}>{(release != null ? ", IDisposable" : "")}\n{{\n");
            sb.Append($$"""
                {{Indent}}/// <summary>The native handle value.</summary>
                {{Indent}}public readonly nint Handle;

                {{Indent}}/// <summary>Wraps a native handle value.</summary>
                {{Indent}}public {{h.Name}}(nint handle) => Handle = handle;

                {{Indent}}/// <summary>The null handle.</summary>
                {{Indent}}public static {{h.Name}} Null => default;

                {{Indent}}/// <summary>Whether this is the null handle.</summary>
                {{Indent}}public bool IsNull => Handle == 0;

                {{Indent}}/// <inheritdoc/>
                {{Indent}}public bool Equals({{h.Name}} other) => Handle == other.Handle;

                {{Indent}}/// <inheritdoc/>
                {{Indent}}public override bool Equals(object? obj) => obj is {{h.Name}} other && Equals(other);

                {{Indent}}/// <inheritdoc/>
                {{Indent}}public override int GetHashCode() => Handle.GetHashCode();

                {{Indent}}/// <inheritdoc/>
                {{Indent}}public override string ToString() => $"{{h.Name}}(0x{Handle:X})";

                {{Indent}}/// <summary>Compares two handles by value.</summary>
                {{Indent}}public static bool operator ==({{h.Name}} left, {{h.Name}} right) => left.Handle == right.Handle;

                {{Indent}}/// <summary>Compares two handles by value.</summary>
                {{Indent}}public static bool operator !=({{h.Name}} left, {{h.Name}} right) => left.Handle != right.Handle;

                {{Indent}}/// <summary>Gets the native handle value.</summary>
                {{Indent}}public static explicit operator nint({{h.Name}} value) => value.Handle;

                """);

            if (release != null)
            {
                sb.Append($"\n{Indent}/// <summary>\n")
                  .Append($"{Indent}/// Releases one reference (<c>{release.Name}</c>). Does nothing for the null handle.\n")
                  .Append($"{Indent}/// Handles are plain values: dispose each reference exactly once, not every copy.\n")
                  .Append($"{Indent}/// </summary>\n")
                  .Append($"{Indent}public void Dispose()\n{Indent}{{\n")
                  .Append($"{Indent}{Indent}if (Handle != 0)\n{Indent}{Indent}{{\n")
                  .Append($"{Indent}{Indent}{Indent}{Lib}.{release.Name}(this);\n")
                  .Append($"{Indent}{Indent}}}\n{Indent}}}\n\n");
            }

            foreach (FunctionDef f in methods)
            {
                string method = f.Name[(4 + h.Name.Length - 4)..];
                EmitCallable(sb, Indent, f, method, isStatic: false, f.Params.Skip(1).ToList(), args => $"{Lib}.{f.Name}({string.Join(", ", args.Prepend("this"))})", receiver: h.Name);
            }

            sb.Append("}\n\n");
        }

        return sb.ToString().TrimEnd() + "\n";
    }

    // ---------------------------------------------------------------- functions

    /// <summary>Free functions that take a struct by value as first argument, e.g. <c>wgpuAdapterInfoFreeMembers</c>, become struct methods.</summary>
    public string EmitStructMethods()
    {
        var sb = new StringBuilder(Header());
        foreach (var group in _m.Functions
            .Where(f => f.Params.Count > 0 && f.Params[0].Type.Pointers == 0 && _structs.ContainsKey(f.Params[0].Type.Base)
                        && f.Name.StartsWith("wgpu" + f.Params[0].Type.Base[4..], StringComparison.Ordinal))
            .GroupBy(f => f.Params[0].Type.Base))
        {
            sb.Append($"public unsafe partial struct {group.Key}\n{{\n");
            foreach (FunctionDef f in group)
            {
                string method = f.Name[group.Key.Length..];
                EmitCallable(sb, Indent, f, method, isStatic: false, f.Params.Skip(1).ToList(), args => $"{Lib}.{f.Name}({string.Join(", ", args.Prepend("this"))})");
            }

            sb.Append("}\n\n");
        }

        return sb.ToString().TrimEnd() + "\n";
    }

    public string EmitFunctions()
    {
        var sb = new StringBuilder(Header());
        sb.Append($"/// <summary>Raw <c>webgpu.h</c> / <c>wgpu.h</c> entry points, constants and convenience overloads.</summary>\n");
        sb.Append($"public static unsafe partial class {Lib}\n{{\n");
        sb.Append($"{Indent}/// <summary>The wgpu-native version these bindings were generated for (<c>eng/native.lock.json</c>).</summary>\n");
        sb.Append($"{Indent}public const string BindingsVersion = \"{_version}\";\n\n");

        foreach (ConstantDef c in _m.Constants)
        {
            DocText.Write(sb, Indent, c.Doc);
            sb.Append(c.Value switch
            {
                "UINT32_MAX" => $"{Indent}public const uint {c.Name} = uint.MaxValue;\n\n",
                "UINT64_MAX" => $"{Indent}public const ulong {c.Name} = ulong.MaxValue;\n\n",
                "SIZE_MAX" => $"{Indent}public static nuint {c.Name} => nuint.MaxValue;\n\n",
                "NAN" => $"{Indent}public const float {c.Name} = float.NaN;\n\n",
                _ when UintCRegex().Match(c.Value) is { Success: true } u => $"{Indent}public const uint {c.Name} = {u.Groups[1].Value};\n\n",
                _ => throw new FormatException($"Unsupported constant {c.Name} = {c.Value}"),
            });
        }

        foreach (FunctionDef f in _m.Functions)
        {
            DocText.Write(sb, Indent, f.Doc, f.Params.Select(p => p.Name).ToList(), extra: UnimplementedNote(f));
            sb.Append(ObsoleteAttribute(f, Indent));
            sb.Append($"{Indent}[LibraryImport(LibraryName, EntryPoint = \"{f.Name}\")]\n");
            sb.Append($"{Indent}[UnmanagedCallConv(CallConvs = [typeof(CallConvCdecl)])]\n");
            sb.Append($"{Indent}public static partial {Cs(f.Return)} {f.Name}({string.Join(", ", RawParams(f.Params, withDefaults: false))});\n\n");
        }

        foreach (FunctionDef f in _m.Functions.Where(f => OwnerOf(f) == null))
        {
            EmitCallable(sb, Indent, f, f.Name, isStatic: true, f.Params, args => $"{f.Name}({string.Join(", ", args)})", rawAlreadyEmitted: true);
        }

        return sb.ToString().TrimEnd() + "\n}\n";
    }

    private IEnumerable<string> RawParams(List<ParamDef> ps, bool withDefaults)
    {
        // Trailing nullable pointers get "= null" so e.g. device.CreateCommandEncoder() works.
        int firstDefault = ps.Count;
        if (withDefaults)
        {
            while (firstDefault > 0 && ps[firstDefault - 1] is { Nullable: true, Type.Pointers: > 0 })
            {
                firstDefault--;
            }
        }

        return ps.Select((p, i) => $"{Cs(p.Type)} {Naming.Identifier(p.Name)}{(i >= firstDefault ? " = null" : "")}");
    }

    /// <summary>Emits the raw forwarding method (unless already emitted) plus the friendly overloads.</summary>
    private void EmitCallable(StringBuilder sb, string indent, FunctionDef f, string name, bool isStatic, List<ParamDef> ps, Func<IEnumerable<string>, string> call, bool rawAlreadyEmitted = false, string? receiver = null)
    {
        string ret = Cs(f.Return);
        string retKw = ret == "void" ? "" : "return ";
        string mod = isStatic ? "static " : "";
        string fullDoc = $"Calls <c>{f.Name}</c>." + (UnimplementedNote(f) is { } note ? " " + note : "");

        if (!rawAlreadyEmitted)
        {
            DocText.Write(sb, indent, f.Doc, ps.Select(p => p.Name).ToList(), extra: fullDoc);
            sb.Append(ObsoleteAttribute(f, indent));
            string signature = $"{indent}public {mod}{Hides(name)}{ret} {name}({string.Join(", ", RawParams(ps, withDefaults: true))})";
            string forward = call(ps.Select(p => Naming.Identifier(p.Name)));
            List<string> checks = Checks(receiver, ps, pointers: true);
            if (checks.Count == 0)
            {
                sb.Append($"{signature} => {forward};\n\n");
            }
            else
            {
                sb.Append($"{signature}\n{indent}{{\n");
                foreach (string check in checks)
                {
                    sb.Append($"{indent}{Indent}{check}\n");
                }

                sb.Append($"{indent}{Indent}{retKw}{forward};\n{indent}}}\n\n");
            }
        }

        foreach (bool stringMode in new[] { false, true })
        {
            Plan? plan = BuildPlan(ps, stringMode);
            if (plan == null)
            {
                continue;
            }

            DocText.Write(sb, indent, f.Doc, plan.ParamNames, extra: fullDoc);
            sb.Append(ObsoleteAttribute(f, indent));
            string generic = plan.Generic ? "<TData>" : "";
            string where = plan.Generic ? " where TData : unmanaged" : "";
            sb.Append($"{indent}public {mod}{Hides(name)}{ret} {name}{generic}({string.Join(", ", plan.Signature)}){where}\n{indent}{{\n");
            string inner = indent + Indent;
            // The friendly overloads turn pointers into spans, `in` parameters and strings, which can't be null.
            foreach (string check in Checks(receiver, ps, pointers: false))
            {
                sb.Append($"{inner}{check}\n");
            }
            foreach (string u in plan.Usings)
            {
                sb.Append($"{inner}{u}\n");
            }

            if (plan.Fixed.Count == 0)
            {
                sb.Append($"{inner}{retKw}{call(plan.Args)};\n");
            }
            else
            {
                foreach (string fx in plan.Fixed)
                {
                    sb.Append($"{inner}fixed ({fx})\n");
                }

                sb.Append($"{inner}{{\n{inner}{Indent}{retKw}{call(plan.Args)};\n{inner}}}\n");
            }

            sb.Append($"{indent}}}\n\n");
        }
    }

    /// <summary>
    /// Argument checks for a generated method: wgpu-native aborts the process on a null handle, a missing descriptor
    /// or an undefined enum value, so the method throws first (see <c>Check</c> in the library). <paramref name="receiver"/>
    /// is the handle type the method is called on. Nullable parameters and arrays (count + pointer, which C allows to be
    /// null when empty) aren't checked.
    /// </summary>
    private List<string> Checks(string? receiver, List<ParamDef> ps, bool pointers)
    {
        var checks = new List<string>();
        if (receiver != null)
        {
            checks.Add($"if (IsNull) Check.ThrowNullHandle(\"{receiver}\");");
        }

        for (int i = 0; i < ps.Count; i++)
        {
            ParamDef p = ps[i];
            string pn = Naming.Identifier(p.Name);
            if (p.Nullable || (i > 0 && IsCountPair(ps[i - 1], p)))
            {
                continue;
            }

            string type = _enumRedirects.GetValueOrDefault(p.Type.Base, p.Type.Base);
            if (p.Type.Pointers == 0 && _handles.ContainsKey(p.Type.Base))
            {
                checks.Add($"if ({pn}.IsNull) Check.ThrowNullArgument(nameof({pn}));");
            }
            else if (p.Type.Pointers == 0 && _enums.TryGetValue(type, out EnumDef? e) && IsCheckedEnum(e))
            {
                checks.Add($"if (!WGPUEnumChecks.IsDefined({pn})) Check.ThrowUndefined(nameof({pn}), {pn});");
            }
            else if (pointers && p.Type.Pointers == 1 && _structs.ContainsKey(p.Type.Base))
            {
                checks.Add($"if ({pn} == null) Check.ThrowNullArgument(nameof({pn}));");
            }
        }

        return checks;
    }

